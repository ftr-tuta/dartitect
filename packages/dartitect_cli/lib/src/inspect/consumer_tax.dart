final _publicSymbol = RegExp(r'\b[A-Z][A-Za-z0-9_]*\b');
final _listener = RegExp(r'\.(?:addListener|removeListener|listen)\s*\(');
final _lifecycle = RegExp(r'\.(?:dispose|disposeAsync|close|cancel)\s*\(');
